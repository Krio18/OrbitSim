inline void draw(SDL_Renderer* r, const std::string& text, int x, int y,
                 SDL_Color color, int scale = 1)
{
    if (!r) return;
    SDL_SetRenderDrawColor(r, color.r, color.g, color.b, color.a);
    int cx = x;
    for (unsigned char c : text) {
        if (c < 32 || c > 126) { cx += (8 + 1) * scale; continue; }
        const uint8_t* glyph = DATA[c - 32];
        for (int row = 0; row < 8; row++) {
            for (int col = 0; col < 8; col++) {
                if (glyph[row] & (1u << col)) {
                    if (scale == 1) {
                        SDL_RenderDrawPoint(r, cx + col, y + row);
                    } else {
                        const SDL_Rect px{cx + col * scale, y + row * scale, scale, scale};
                        SDL_RenderFillRect(r, &px);
                    }
                }
            }
        }
        cx += (8 + 1) * scale;
    }
}

inline void drawShadow(SDL_Renderer* r, const std::string& text, int x, int y,
                       SDL_Color color, int scale = 1)
{
    draw(r, text, x + scale, y + scale, {0, 0, 0, 200}, scale);
    draw(r, text, x, y, color, scale);
}

inline int textWidth(const std::string& text, int scale = 1) {
    return static_cast<int>(text.size()) * (8 + 1) * scale;
}

